#!/usr/bin/env node
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const pkgPath = "package.json";
const buildIdPath = ".build-id";
const versionPath = "src/shared/version.ts";

const pkg = JSON.parse(readFileSync(pkgPath, "utf8"));
const version = pkg.version;

const buildId = existsSync(buildIdPath)
  ? Number.parseInt(readFileSync(buildIdPath, "utf8"), 10) + 1
  : 1;

writeFileSync(buildIdPath, String(buildId));

const buildTime = new Date().toISOString();

writeFileSync(
  versionPath,
  `// Auto-generated by scripts/generate-build-id.mjs — do not edit manually\nexport const VERSION = "${version}";\nexport const BUILD_ID = ${buildId};\nexport const BUILD_TIME = "${buildTime}";\nexport const BUILD_LABEL = "${version}+b${buildId}";\n`,
);

console.log(`[Gerrit Hero] build ${version}+b${buildId} (${buildTime})`);
